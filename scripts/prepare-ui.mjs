import { readFile, writeFile, mkdir, cp } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => readFile(path.join(root, file), 'utf8');
// Classic scripts deliberately share lexical scope. Do not reorder: extensions
// decorate the base renderer and depend on earlier feature declarations.
export const sources = [
  'public/vendor/jquery.min.js',
  'public/vendor/leaflet.js',
  'src/features/workspace/runtime.js',
  'src/features/reports/reports.js',
  'public/data/road-routes.js',
  'src/features/deliveries/rider-map.js',
  'src/features/policies/rule-catalog.js',
  'src/features/priority/priority-engine.js',
  'src/features/policies/rule-engine.js',
  'src/features/exceptions/maker-checker.js',
  'src/features/policies/rule-controls.js',
  'src/features/priority/priority-controls.js',
  'src/features/workspace/sme-workspace.js',
];
await mkdir(path.join(root, 'public'), { recursive: true });
const chunks = await Promise.all(sources.map(read));
await writeFile(path.join(root, 'public/workspace.js'), chunks.join('\n;\n') + '\n');
const shell = await read('src/features/workspace/shell.html');
const styles = await read('src/features/workspace/styles.css') + '\n' + await read('src/features/workspace/theme.css');
await writeFile(path.join(root, 'src/features/workspace/generated.ts'),
  '// Generated by prepare-ui.mjs. Edit shell.html/styles.css instead.\n' +
  `export const shell = ${JSON.stringify(shell)};\nexport const styles = ${JSON.stringify(styles)};\n`);
console.log('Prepared workspace markup, styles, feature runtime and language assets.');

await writeFile(path.join(root, 'public/language.js'), 'window.ParcelCareEnglish = ' + await read('public/locales/en.json') + ';\nwindow.ParcelCareMyanmar = ' + await read('public/locales/my.json') + ';\n' + await read('src/shared/i18n/runtime.js'));

await writeFile(path.join(root, 'dist/language.js'), await read('public/language.js'));

await cp(path.join(root,'public/fonts'),path.join(root,'dist/fonts'),{recursive:true});
